import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../src/app.js', import.meta.url), 'utf8');
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(source.slice(source.indexOf("'use strict';"), source.indexOf('/* ── leaflet map controller')) + '\nglobalThis.route = MISSIONS.route;', sandbox);
const route = sandbox.route;
const c = { ...route.defaults, vertices: [{ lat: 58.9, lon: 5.7 }, { lat: 58.91, lon: 5.71 }, { lat: 58.92, lon: 5.72 }], ground: 100, speed: 4, trigger: 'waypoint' };
const points = route.buildWaypoints(c);
assert.equal(points.length, 3);
points.forEach((wp, i) => {
  assert.equal(wp.location.lat, c.vertices[i].lat);
  assert.equal(wp.location.lon, c.vertices[i].lon);
  assert.equal(wp.location.alt, 130);
  assert.equal(wp.headingMode, 'towardPOI');
  assert.equal(wp.poiCoordinate.lat, Number(c.POI.lat.toFixed(7)));
  assert.equal(wp.poiCoordinate.lon, Number(c.POI.lon.toFixed(7)));
  assert.equal(wp.actions[0].parameters.gimbalRotate.pitch, -30);
  assert.equal(wp.actions[1].type, 'takePhoto');
});
assert.equal(route.validate(c).errs.length, 0);
assert.ok(route.validate({ ...c, vertices: [] }).errs.length);
assert.ok(route.validate({ ...c, POI: { lat: 100, lon: 0 } }).errs.length);
assert.ok(route.validate({ ...c, alt: -1 }).errs.length);
const follow = route.buildWaypoints({ ...c, yawMode: 'followWayline', trigger: 'none' });
assert.equal(follow[0].headingMode, 'followWayline');
assert.equal(follow[0].poiCoordinate, undefined);
assert.equal(follow[0].actions.length, 1);
const fixed = route.buildWaypoints({ ...c, yawMode: 'fixed', fixedHeading: 75 });
assert.equal(fixed[0].actions[0].parameters.rotateYaw.aircraftHeading, 75);
vm.runInContext("state.activeMissionType = 'route'; ensureDefaults('route'); editableVertices().push({lat: 1, lon: 2});", sandbox);
assert.equal(sandbox.editableVertices().length, 1);
vm.runInContext("state.activeMissionType = 'corridor';", sandbox);
assert.notEqual(sandbox.editableVertices().length, 1);
vm.runInContext("state.activeMissionType = 'route';", sandbox);
assert.equal(sandbox.editableVertices().length, 1);
console.log('Route order, POI, altitude, camera actions, heading modes, validation and isolated route storage passed.');
